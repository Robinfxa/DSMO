// Phone layout screenshots (dark, 360×780 @3x like the reference screenshots) + interactions.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mkdirSync } from 'node:fs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const here = dirname(fileURLToPath(import.meta.url));
const url = 'file://' + join(here, '..', 'dist-proto', 'index.html');
const shots = join(here, 'shots', 'm');
mkdirSync(shots, { recursive: true });
const errors = [];
const scheme = process.argv[2] || 'dark';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 360, height: 780 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, colorScheme: scheme });
const page = await ctx.newPage();
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
await page.goto(url);
await page.waitForTimeout(700);
const shot = (n) => page.screenshot({ path: join(shots, `${scheme}-${n}.png`) });
const longPress = async (sel) => {
  const b = await page.locator(sel).first().boundingBox();
  await page.dispatchEvent(sel, 'touchstart', { touches: [{ identifier: 1, clientX: b.x + 20, clientY: b.y + b.height / 2 }] }).catch(() => {});
  await page.waitForTimeout(600);
  await page.dispatchEvent(sel, 'touchend', { touches: [] }).catch(() => {});
  await page.waitForTimeout(250);
};
await shot('01-home');
await page.click('[aria-label="添加附件"]');
await page.waitForTimeout(350);
await shot('02-attach');
await page.click('[aria-label="收起"]');
await page.click('[aria-label="打开边栏"]');
await page.waitForTimeout(450);
await shot('03-drawer');
await page.click('[aria-label="多选"]');
await page.waitForTimeout(350);
await shot('04a-multiselect-empty');
await page.click('.m-item.picking >> nth=1');
await shot('04-multiselect');
await page.click('.m-pick-bar button:has-text("置顶")');
await page.waitForTimeout(350);
await shot('05-alert');
await page.click('.m-alert-btns .primary');
await page.waitForTimeout(500);
await shot('06-pinned');
await page.click('.m-item-t >> nth=0');
await page.waitForTimeout(700);
await shot('07-chat');
await longPress('.bubble');
await shot('08-user-menu');
await page.click('.m-pop-row:has-text("修改")');
await page.waitForTimeout(300);
await shot('09-edit');
await page.click('[aria-label="取消修改"]');
await page.click('[aria-label="打开边栏"]');
await page.waitForTimeout(400);
await page.click('.m-item.on .m-item-more');
await page.waitForTimeout(250);
await shot('10-item-menu');
await page.click('.m-pop-layer', { position: { x: 5, y: 5 } });
await page.click('.m-me [aria-label="设置"]');
await page.waitForTimeout(450);
await shot('11-settings');
await page.click('.m-row:has-text("字体大小")');
await page.waitForTimeout(400);
await shot('12-font');
await page.click('[aria-label="返回"] >> nth=-1');
await page.waitForTimeout(350);
await page.click('.m-row:has-text("数据管理")');
await page.waitForTimeout(400);
await shot('13-data');
await page.click('[aria-label="返回"] >> nth=-1');
await page.waitForTimeout(350);
await page.click('[role="switch"][aria-label="高级模式"]');
await page.waitForTimeout(200);
await shot('14-settings-adv');
await page.click('[aria-label="返回"] >> nth=-1');
await page.waitForTimeout(400);
// new chat, send, reply with actions
await page.click('[aria-label="开启新对话"]');
await page.fill('#input', '把花销做成表');
await page.click('#sendBtn');
await page.waitForFunction(() => document.querySelector('.a-text')?.textContent?.includes('332.70'), null, { timeout: 15000 });
await page.waitForTimeout(400);
await shot('15-reply');
await page.click('[aria-label="打开边栏"]');
await page.waitForTimeout(400);
await shot('16-drawer-adv');
await page.click('.m-search');
await page.waitForTimeout(400);
await page.fill('.m-search.field input', '1');
await page.waitForTimeout(500);
await shot('17-search');
await browser.close();
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
