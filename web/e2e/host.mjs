// The rebuilt engine pages on the phone: 工作区, 引擎设置, 引擎插件, 模型提供方, 自动化任务, 终端.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mkdirSync } from 'node:fs';
import { openFeats } from './feats.mjs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const here = dirname(fileURLToPath(import.meta.url));
const url = 'file://' + join(here, '..', 'dist-proto', 'index.html');
const shots = join(here, 'shots', 'h');
mkdirSync(shots, { recursive: true });
const errors = [];
const scheme = process.argv[2] || 'light';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 360, height: 780 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, colorScheme: scheme });
const page = await ctx.newPage();
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
await page.goto(url);
await page.waitForTimeout(700);
const shot = (n) => page.screenshot({ path: join(shots, `${scheme}-${n}.png`) });
const tall = async (n) => {
  const h = await page.evaluate(() => document.querySelector('.pg-body')?.scrollHeight ?? 780);
  await page.setViewportSize({ width: 360, height: Math.min(h + 70, 2400) });
  await page.waitForTimeout(200);
  await shot(n);
  await page.setViewportSize({ width: 360, height: 780 });
};
const back = async () => (await page.click('[aria-label="返回"] >> nth=-1'), await page.waitForTimeout(350));
const settings = async () => {
  await page.click('[aria-label="打开边栏"]');
  await page.waitForTimeout(400);
  await page.click('.m-me [aria-label="设置"]');
  await page.waitForTimeout(450);
};
await settings();
await page.click('[role="switch"][aria-label="高级模式"]');
await page.waitForTimeout(200);
await shot('00-settings');
// 工作区
await page.click('.m-row:has-text("工作区")');
await page.waitForTimeout(500);
await page.click('.plg-link:has-text("添加工作区")');
await page.waitForTimeout(400);
await page.click('.plg-link:has-text("projects")');
await page.waitForTimeout(300);
await page.click('.plg-link:has-text("api-demo")');
await page.waitForTimeout(300);
await shot('01-picker');
await page.click('.plg-btn.pri');
await page.waitForTimeout(500);
await shot('02-workspaces');
await back();
// 引擎设置
await settings();
await page.click('.m-row:has-text("引擎设置")');
await page.waitForTimeout(500);
await shot('03-engine-settings');
await page.click('.plg-link:has-text("命令执行")');
await page.waitForTimeout(500);
await page.fill('.sf-num >> nth=0', '300');
await page.keyboard.press('Tab');
await page.waitForTimeout(400);
await tall('04-shell-settings');
await back();
await back();
// 引擎插件
await settings();
await page.click('.m-row:has-text("引擎插件")');
await page.waitForTimeout(500);
await page.fill('.sf-input.wide', 'dsh-plugin-notes@1.0.0');
await page.click('.plg-get:has-text("安装")');
await page.waitForTimeout(400);
await page.click('.m-alert-btns button >> nth=-1');
await page.waitForTimeout(500);
await tall('05-engine-plugins');
await back();
// 模型提供方
await settings();
await page.click('.m-row:has-text("模型提供方")');
await page.waitForTimeout(500);
await page.click('.plg-link:has-text("添加提供方")');
await page.waitForTimeout(400);
await page.fill('input[placeholder="例如 moonshot"]', 'moonshot');
await page.fill('input[placeholder="https://…/v1"]', 'https://api.moonshot.cn/v1');
await page.fill('input[placeholder="只保存在主机上"]', 'sk-test');
await page.click('.plg-link:has-text("获取模型列表")');
await page.waitForTimeout(500);
await shot('06-provider-new');
await page.click('.plg-btn.pri:has-text("添加")');
await page.waitForTimeout(600);
await shot('07-providers');
await page.click('.plg-row:has-text("moonshot")');
await page.waitForTimeout(600);
await tall('08-provider-detail');
await back();
await back();
// 自动化任务
await page.click('[aria-label="打开边栏"]');
await page.waitForTimeout(400);
await openFeats(page);
await page.click('.m-frow:has-text("自动化任务")');
await page.waitForTimeout(500);
await page.click('.plg-link:has-text("新建自动化任务")');
await page.waitForTimeout(300);
await page.fill('input[placeholder="例如：每日计划"]', '每周复盘');
await page.selectOption('.sf-select', 'weekly');
await page.click('.wd:has-text("五")');
await page.fill('.pg-body textarea.sf-input', '回顾这周做了什么，列出下周三件事。');
await shot('09-schedule-new');
await page.click('.plg-btn.pri:has-text("创建")');
await page.waitForTimeout(600);
await shot('10-schedules');
await page.click('.plg-row:has-text("每周复盘")');
await page.waitForTimeout(600);
await page.click('.plg-link:has-text("立即运行一次")');
await page.waitForTimeout(800);
await tall('11-schedule-detail');
await back();
await back();
// 终端（从对话的 ⋯）
await page.click('[aria-label="打开边栏"]');
await page.waitForTimeout(400);
await page.click('.m-item-t >> nth=0');
await page.waitForTimeout(600);
await page.click('.h-more');
await page.waitForTimeout(400);
await page.click('.cm-item:has-text("终端")');
await page.waitForTimeout(1500);
await page.click('.term-box');
await page.keyboard.type('ls');
await page.keyboard.press('Enter');
await page.keyboard.type('cd /root/projects');
await page.keyboard.press('Enter');
await page.keyboard.type('ls');
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
await shot('12-terminal');
const txt = await page.evaluate(() => document.querySelector('.xterm-rows')?.textContent ?? '');
if (!txt.includes('valueagents')) errors.push('terminal did not run ls in projects: ' + txt.slice(0, 200));
await browser.close();
console.log(errors.length ? errors.join('\n') : 'no errors');
