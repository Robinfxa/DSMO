// Round 2 pages on the phone: 远程主机 (with trust-on-first-use), 本机引擎, 通知, 识别方式, 更新, 系统权限, 手机操控.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mkdirSync } from 'node:fs';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const here = dirname(fileURLToPath(import.meta.url));
const url = 'file://' + join(here, '..', 'dist-proto', 'index.html');
const shots = join(here, 'shots', 'l');
mkdirSync(shots, { recursive: true });
const errors = [];
const scheme = process.argv[2] || 'light';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 360, height: 780 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, colorScheme: scheme });
const page = await ctx.newPage();
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
await page.goto(url);
await page.waitForTimeout(700);
const shot = (n) => page.screenshot({ path: join(shots, `${scheme}-${n}.png`) });
const tall = async (n) => {
  const h = await page.evaluate(() => document.querySelector('.pg-body')?.scrollHeight ?? 780);
  await page.setViewportSize({ width: 360, height: Math.min(h + 70, 2400) });
  await page.waitForTimeout(200);
  await shot(n);
  await page.setViewportSize({ width: 360, height: 780 });
};
const back = async () => (await page.click('[aria-label="返回"] >> nth=-1'), await page.waitForTimeout(350));
const settings = async () => {
  await page.click('[aria-label="打开边栏"]');
  await page.waitForTimeout(400);
  await page.click('.m-me [aria-label="设置"]');
  await page.waitForTimeout(450);
};
const row = async (label) => (await page.click(`.m-row:has-text("${label}")`), await page.waitForTimeout(500));
await settings();
await page.click('[role="switch"][aria-label="高级模式"]');
await page.waitForTimeout(200);
await tall('00-settings');
// 远程主机
await row('远程主机');
await shot('01-hosts');
await page.click('.plg-link:has-text("添加 SSH 主机")');
await page.waitForTimeout(400);
await page.fill('input[placeholder="例如：家里的电脑"]', '实验室服务器');
await page.fill('input[placeholder="192.168.1.20 或 my.host"]', 'lab.example.edu');
await page.fill('input[placeholder="me"]', 'robin');
await page.fill('.pg-body input[type="password"]', 'hunter2');
await page.click('.plg-btn:has-text("测试连接")');
await page.waitForSelector('.m-alert', { timeout: 5000 });
await page.waitForTimeout(200);
await shot('02-hostkey');
await page.click('.m-alert-btns button >> nth=-1');
await page.waitForTimeout(2200);
await tall('03-tested');
const fp = await page.textContent('.plg-kv >> nth=0');
if (!/SHA256/.test(fp)) errors.push('host key not pinned after test: ' + fp);
await page.click('.plg-btn.pri:has-text("保存")');
await page.waitForTimeout(600);
await shot('04-hosts-added');
await page.click('.plg-row:has-text("实验室服务器")');
await page.waitForTimeout(500);
await shot('05-switched');
await back();
// 本机引擎
await settings();
await row('本机引擎');
await page.click('.plg-btn:has-text("重启")');
await page.waitForTimeout(600);
await shot('06-engine-restarting');
await page.waitForTimeout(2200);
await page.click('.plg-link:has-text("查看日志")');
await page.waitForTimeout(300);
await tall('07-engine');
await back();
// 通知
await settings();
await row('通知');
await page.click('[role="switch"][aria-label="实时活动"]');
await page.waitForTimeout(300);
await shot('08-notify');
await back();
// 识别方式
await settings();
await row('识别方式');
await page.click('.plg-row:has-text("本机引擎")');
await page.waitForTimeout(300);
await shot('09-voice');
await back();
// 更新
await settings();
await row('检查更新');
await page.click('.plg-btn:has-text("检查更新")');
await page.waitForTimeout(1200);
await page.click('.plg-btn.pri:has-text("下载")');
await page.waitForTimeout(800);
await shot('10-update-downloading');
await page.waitForTimeout(2500);
await shot('11-update-ready');
await back();
// 系统权限
await settings();
await row('系统权限');
await page.click('.plg-row:has-text("不受电池优化限制")');
await page.waitForTimeout(700);
await tall('12-access');
await back();
// 手机操控
await settings();
await row('手机操控');
await shot('13-phone-disclosure');
await page.click('.plg-btn:has-text("继续")');
await page.waitForTimeout(500);
await page.click('.plg-row:has-text("无障碍")');
await page.waitForTimeout(900);
await page.click('[role="switch"][aria-label="手机操控"]');
await page.waitForTimeout(500);
await page.click('.plg-link:has-text("读当前屏幕")');
await page.waitForTimeout(800);
await shot('14-phone');
await browser.close();
console.log(errors.length ? errors.join('\n') : 'no errors');
