#!/usr/bin/env bash
# Applies the DSMO patch set to a dsh-Go checkout (decision Q2: we only
# maintain what we change).
#
#   native/apply.sh <path-to-dsh-go> [--skip-web]
#
# 1. checks the dsh-Go commit the patches were written against
# 2. `git am` the patches in native/patches/ (3-way, so small upstream drift merges)
# 3. copies native/overlay/ (new files only, e.g. app/lib/api_demo/) into the checkout
# 4. builds web/ and copies web/dist into app/assets/api_demo/
# 6. deletes what DSMO doesn't ship (binary files, which patch 0012 leaves out so the patch
#    doesn't carry them): dsh-Go's mascot art (not AGPL, ASSETS.md) — Deepy and the whale girl,
#    the Star sticker, the whale tails, the 伙伴小屋 widget's pixel whale — the pet and 伙伴小屋
#    skills, and the voice-call turn models (DSMO has no voice calls; dictation doesn't use them,
#    and the call code falls back to its energy gate without them).
# 5. replaces DSH Go's brand art (not AGPL) with ours: the launcher icons from native/brand/res/,
#    and the in-app mark (launch screen, drawer, About) from native/brand/masters/ through
#    dsh-Go's own app/tool/make_brand_mark.py. native/brand/make_brand.py makes both.
#
# Then build as dsh-Go documents it (runtime/build-runtime.sh + tooling/build-apk.sh),
# or run native/build-apk.sh, which does all of it.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/.." && pwd)"
target="${1:?usage: native/apply.sh <path-to-dsh-go> [--skip-web]}"
skip_web="${2:-}"
base="$(cat "$here/BASE")"

cd "$target"
git rev-parse --git-dir >/dev/null
head="$(git rev-parse HEAD)"
if [ "$head" != "$base" ]; then
  echo "! dsh-Go is at $head; the patches were written against $base."
  echo "  Trying anyway (3-way). If it stops, see docs/native.md › 跟进上游."
fi
if [ -n "$(git status --porcelain)" ]; then
  echo "✗ the dsh-Go checkout has local changes; commit or stash them first" >&2
  exit 1
fi

echo "→ patches"
git -c user.name="DSMO" -c user.email="dsmo@users.noreply.github.com" am --3way "$here"/patches/*.patch

echo "→ overlay"
(cd "$here/overlay" && find . -type f) | while read -r f; do
  if [ -e "$target/$f" ]; then
    echo "✗ overlay file $f already exists in dsh-Go: overlay only adds files" >&2
    exit 1
  fi
  mkdir -p "$target/$(dirname "$f")"
  cp "$here/overlay/$f" "$target/$f"
done

if [ "$skip_web" != "--skip-web" ]; then
  echo "→ web"
  (cd "$repo/web" && npm ci && npm run build)
fi
rm -rf "$target/app/assets/api_demo"
mkdir -p "$target/app/assets/api_demo"
cp -R "$repo/web/dist/." "$target/app/assets/api_demo/"

echo "→ brand"
res="$target/app/android/app/src/main/res"
cp -R "$here/brand/res/." "$res/"
cp "$here"/brand/masters/*.svg "$target/app/assets/brand/"
(cd "$target/app" && python3 tool/make_brand_mark.py)

echo "→ not shipped"
rm -rf "$target/app/assets/pets" "$target/app/assets/star" "$target/app/assets/whale" \
  "$target/app/assets/skills/companion-adapt" "$target/app/assets/skills/pet-theme" \
  "$target/app/android/app/src/main/res/drawable-nodpi/companion_widget_"*.png \
  "$target/app/android/app/src/main/assets/speech"

git add -A
git -c user.name="DSMO" -c user.email="dsmo@users.noreply.github.com" commit -qm "DSMO: overlay files, bundled frontend and brand art (generated by native/apply.sh)"
echo "✓ done. Next (x86_64 Linux): cd $target && bash runtime/build-runtime.sh arm64-v8a && DSH_BETA_TOKEN_FILE= bash tooling/build-apk.sh -f arm64"
